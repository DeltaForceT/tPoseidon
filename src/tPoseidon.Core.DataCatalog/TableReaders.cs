        ("ESAII_", "LoadSkillInvocationRows"),
        ("ESAll_", "LoadSkillInvocationRows"),
    };

    private static readonly Dictionary<string, string[]> ByName = Exact
        .GroupBy(pair => pair.Table, StringComparer.Ordinal)
        .ToDictionary(group => group.Key, group => group.Select(pair => pair.Reader).ToArray(), StringComparer.Ordinal);

    public static IReadOnlyList<string> Of(string tableName)
    {
        ArgumentNullException.ThrowIfNull(tableName);
        var readers = new List<string>();
        if (ByName.TryGetValue(tableName, out var exact)) readers.AddRange(exact);
        foreach (var (prefix, reader) in Prefixed)
        {
            if (tableName.StartsWith(prefix, StringComparison.Ordinal)) readers.Add(reader);
        }
        return readers;
    }
