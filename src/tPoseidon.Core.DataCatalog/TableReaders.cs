    private static readonly (string Prefix, string Reader)[] Prefixed =
    {
        ("NpcTalk_", "LoadAllNpcTalkTables"),
        ("NpcMsg_", "LoadAllNpcMsgTables"),
        ("RegionInfo_", "LoadAllRegionInfoTables"),
        ("Tactics_Mon", "LoadAllTacticsMonTables"),
