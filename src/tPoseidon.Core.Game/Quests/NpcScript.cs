    public const int RandomMessageArgs = 5;
    public const int GenderCheckArgs = 2;
    public const int HighestGenderedCharacterType = 24;

    public static int GenderResult(int characterType, int argCount)
    {
        if (argCount != GenderCheckArgs || characterType < 1 || characterType > HighestGenderedCharacterType) return Refused;
        return characterType % 2 == 0 ? 1 : 2;
    }

    public static int FTypeResult(int typeIndex, int wanted) => typeIndex == wanted ? 1 : 2;

    public static int? MessageFor(int result, IReadOnlyList<ushort> args)
    {
        ArgumentNullException.ThrowIfNull(args);
        if (result < 1) return null;
        return result <= args.Count ? args[result - 1] : Refused;
    }
