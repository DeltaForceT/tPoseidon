ALTER TABLE characters
    ADD COLUMN IF NOT EXISTS pts_p SMALLINT NOT NULL DEFAULT 0
        CHECK (pts_p BETWEEN 0 AND 255),
    ADD COLUMN IF NOT EXISTS pts_m SMALLINT NOT NULL DEFAULT 0
        CHECK (pts_m BETWEEN 0 AND 255),
    ADD COLUMN IF NOT EXISTS pts_s SMALLINT NOT NULL DEFAULT 0
        CHECK (pts_s BETWEEN 0 AND 255),
    ADD COLUMN IF NOT EXISTS pts_c SMALLINT NOT NULL DEFAULT 0
        CHECK (pts_c BETWEEN 0 AND 255);

UPDATE characters SET
    pts_p = CASE ftype WHEN 1 THEN 6 ELSE 3 END,
    pts_m = CASE ftype WHEN 2 THEN 6 ELSE 3 END,
    pts_s = CASE ftype WHEN 3 THEN 6 ELSE 3 END,
    pts_c = CASE ftype WHEN 4 THEN 6 ELSE 3 END
WHERE pts_p = 0 AND pts_m = 0 AND pts_s = 0 AND pts_c = 0;
